// ==================== CORE FUNCTIONS ====================

const LANG_KEY = "habitat.lang";
let currentLang = "en";

function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && I18N[saved]) return saved;
  } catch (e) { /* ignore */ }
  // Auto-detect browser language
  const nav = (navigator.language || "en").split("-")[0].toLowerCase();
  if (I18N[nav]) return nav;
  return "en";
}

function setLang(code) {
  if (!I18N[code]) code = "en";
  currentLang = code;
  try { localStorage.setItem(LANG_KEY, code); } catch (e) { /* ignore */ }
  // Update RTL
  const langDef = LANGS.find(l => l.code === code);
  const isRtl = langDef && langDef.rtl;
  document.documentElement.dir = isRtl ? "rtl" : "ltr";
  document.documentElement.lang = code;
  // Re-apply static translations
  applyStaticI18n();
}

function t(key) {
  const dict = I18N[currentLang] || I18N.en;
  return dict[key] || I18N.en[key] || key;
}

function applyStaticI18n(root) {
  const scope = root || document;
  const els = scope.querySelectorAll("[data-i18n]");
  els.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  // Also handle data-i18n-placeholder
  const phs = scope.querySelectorAll("[data-i18n-placeholder]");
  phs.forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.placeholder = t(key);
  });
}

// ==================== CONTENT TRANSLATION ====================

/**
 * Translate an array of texts to a target language using MyMemory API.
 * Falls back to original text on error.
 * @param {string[]} texts - Array of strings to translate
 * @param {string} target - Target language code (e.g. "fr", "es")
 * @returns {Promise<string[]>} - Array of translated strings
 */
async function translateAll(texts, target) {
  if (!Array.isArray(texts) || !texts.length) return [];
  if (!target || target === "en") return [...texts];

  // Route through the backend translation proxy so third-party API keys
  // stay server-side and user text never goes directly to a CDN.
  // API_URL and AUTH_TOKEN live in store.js — single source of truth.
  const AUTH_TOKEN = Store ? Store.getToken() : (localStorage.getItem("habitat.token"));
  const API_URL = Store ? Store.API_URL : (window.HABITAT_API_URL || "https://habitat-api.onrender.com");

  try {
    const resp = await fetch(API_URL + "/api/translate", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        ...(AUTH_TOKEN ? { Authorization: "Bearer " + AUTH_TOKEN } : {}),
      },
      body: JSON.stringify({ texts, target }),
    });
    if (!resp.ok) {
      const err = await resp.json().catch(() => ({}));
      throw new Error(err.error || resp.statusText);
    }
    const data = await resp.json();
    // Server returns { translations: [...] }
    if (Array.isArray(data.translations)) return data.translations;
    if (data.translated) return data.translated;
    return texts;
  } catch (e) {
    console.warn("Translation failed:", e.message);
    return texts; // fall back to originals on error, but surface the warning
  }
}

